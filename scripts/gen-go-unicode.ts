// 给 Go 版的句尾清理（native/internal/textclean）生成 Unicode 属性表：用 Bun 自己的正则一个码位一个码位地判，
// 两边认字就是同一份 Unicode（Go 标准库的 unicode 包版本可能和 Bun 的 ICU 不同，新字符会判得不一样）。
// 升级 Bun 以后重跑一次：bun scripts/gen-go-unicode.ts（输出 native/internal/textclean/unicode_gen.go，再 gofmt）
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

// 每个表对应 daemon/util/tail-junk.ts、clean-text.ts、JS 的 trim 里用到的一个判断
const TABLES: Record<string, RegExp> = {
  /** JS 的 \s（带 u）和 String.prototype.trim 去掉的字：WhiteSpace + LineTerminator */
  jsSpace: /\s/u,
  co: /\p{Co}/u,
  cf: /\p{Cf}/u,
  cn: /\p{Cn}/u,
  letterOrMark: /[\p{L}\p{M}]/u,
  allowedScript: /[\p{Script=Han}\p{Script=Latin}\p{Script=Greek}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}\p{Script=Bopomofo}\p{Script=Common}\p{Script=Inherited}]/u,
  han: /\p{Script=Han}/u,
  so: /\p{So}/u,
  emojiPresentation: /\p{Emoji_Presentation}/u,
  punct: /\p{P}/u,
}

const out: string[] = []
out.push('// Code generated by scripts/gen-go-unicode.ts; DO NOT EDIT.')
out.push(`// Bun ${Bun.version}，ICU ${process.versions.icu}，Unicode ${process.versions.unicode}`)
out.push('')
out.push('package textclean')
out.push('')
for (const [name, re] of Object.entries(TABLES)) {
  const ranges: [number, number][] = []
  for (let c = 0; c <= 0x10ffff; c++) {
    if (c >= 0xd800 && c <= 0xdfff) continue   // 代理项：Go 的字符串里不会单独出现
    if (!re.test(String.fromCodePoint(c))) continue
    const last = ranges.at(-1)
    if (last && (last[1] === c - 1 || (last[1] === 0xd7ff && c === 0xe000))) last[1] = c
    else ranges.push([c, c])
  }
  out.push(`var ${name} = table{`)
  for (const [lo, hi] of ranges) out.push(`\t{0x${lo.toString(16)}, 0x${hi.toString(16)}},`)
  out.push('}')
  out.push('')
}
writeFileSync(join(import.meta.dir, '..', 'native', 'internal', 'textclean', 'unicode_gen.go'), out.join('\n'))
console.log('写好了：', Object.keys(TABLES).join('、'))
