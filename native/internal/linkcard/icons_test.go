func TestActionIconsSamePathsAsBefore(t *testing.T) {
	if len(actionIconNames) != len(frozenActionPaths) {
		t.Fatalf("互动图标 %d 个，固定的原文 %d 个", len(actionIconNames), len(frozenActionPaths))
	}
	for name, want := range frozenActionPaths {
		mc, ok := actionIconNames[name]
		if !ok {
			t.Fatalf("少了互动图标 %q", name)
		}
		got, err := icons.Body(mc, false)
		if err != nil {
			t.Fatalf("%s（%s）：%v", name, mc, err)
		}
		if got != want {
			t.Errorf("%s（%s）：路径和原来抄的不一样\n现在 %s\n原来 %s", name, mc, got, want)
		}
		if actionIcons()[name] == nil {
			t.Errorf("%s 没解析出来", name)
		}
	}
}
