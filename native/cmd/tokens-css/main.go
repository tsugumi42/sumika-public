// tokens-css 把设计令牌算成网页用的 CSS 变量（ADR-353：网页界面和 mygo 同一份令牌 JSON，ADR-347）。
// 值用 design.Derive 算（默认外观设置，亮、暗两套），所以和 Go 界面画出来的一模一样；字号、疏密、圆角改了以后的换算第 3 步搬进页面。
//
//	cd native && go run ./cmd/tokens-css -out ../desktop/src/web/tokens.gen.css
//
// 另外输出聊天区（internal/chatui）自己从令牌推出来的量：消息头像、气泡内距、组内组间距、合组时间窗……（--chat-*），
// 网页气泡照它画，和 mygo 一样大。
//
// 变量名 = 分组 + Go 字段名转成小写连字符：--dim-bubble-radius、--color-chat-bg、--motion-fast（毫秒）、--curve-ease-route、--chat-avatar-msg。
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"reflect"
	"strings"
	"time"
	"unicode"

	"github.com/egoist/mygo/ui"

	"sumika-native/internal/chatui"
	"sumika-native/internal/design"
)

func main() {
	out := flag.String("out", "", "写到哪个文件；空就打到标准输出")
	flag.Parse()
	src := render()
	if *out == "" {
		os.Stdout.Write(src)
		return
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "写 CSS 令牌失败：", err)
		os.Exit(1)
	}
}

func render() []byte {
	var b bytes.Buffer
	b.WriteString("/* Code generated by native/cmd/tokens-css from native/internal/design/tokens; DO NOT EDIT. */\n")
	light := design.DefaultSettings()
	dark := light
	dark.Dark = true
	block(&b, ":root", design.Derive(light), true)
	block(&b, ":root[data-theme=\"dark\"]", design.Derive(dark), false)
	return b.Bytes()
}

// block 写一组变量；all 为假时只写颜色（尺寸、时长、曲线亮暗一样，不重复）。
func block(b *bytes.Buffer, sel string, t design.Tokens, all bool) {
	fmt.Fprintf(b, "%s {\n", sel)
	if all {
		fields(b, "dim", reflect.ValueOf(t.Dim))
		fields(b, "num", reflect.ValueOf(t.Num))
		fields(b, "motion", reflect.ValueOf(t.Motion))
		fields(b, "curve", reflect.ValueOf(t.Curve))
		fields(b, "breakpoint", reflect.ValueOf(t.Breakpoint))
		chat(b, chatui.Derive(chatui.DefaultSettings()))
	}
	fields(b, "color", reflect.ValueOf(t.Color))
	accent(b, t.AccentOf(chatui.DefaultChar.Design()))
	if !all {
		b.WriteString("  color-scheme: dark;\n")
	} else {
		b.WriteString("  color-scheme: light;\n")
	}
	b.WriteString("}\n")
}

func fields(b *bytes.Buffer, group string, v reflect.Value) {
	ty := v.Type()
	for i := range ty.NumField() {
		f := ty.Field(i)
		if !f.IsExported() {
			continue
		}
		val, ok := cssValue(v.Field(i).Interface())
		if !ok {
			continue
		}
		fmt.Fprintf(b, "  --%s-%s: %s;\n", group, kebab(f.Name), val)
	}
}

func cssValue(x any) (string, bool) {
	switch v := x.(type) {
	case float32:
		return num(float64(v)), true
	case float64:
		return num(v), true
	case int:
		return fmt.Sprint(v), true
	case time.Duration:
		return fmt.Sprintf("%dms", v.Milliseconds()), true
	case [4]float32:
		return fmt.Sprintf("cubic-bezier(%s, %s, %s, %s)", num(float64(v[0])), num(float64(v[1])), num(float64(v[2])), num(float64(v[3]))), true
	case ui.Color:
		return fmt.Sprintf("rgb(%d %d %d / %s)", v.R, v.G, v.B, num(float64(v.A)/255)), true
	}
	return "", false
}

// num 写成最短的小数；尺寸在 CSS 里配单位由使用处 calc(var(--dim-x) * 1px)，这里只给数。
func num(v float64) string {
	s := strings.TrimRight(strings.TrimRight(fmt.Sprintf("%.4f", v), "0"), ".")
	if s == "-0" || s == "" {
		return "0"
	}
	return s
}

func kebab(s string) string {
	var b strings.Builder
	for i, r := range s {
		if unicode.IsUpper(r) {
			if i > 0 {
				b.WriteByte('-')
			}
			b.WriteRune(unicode.ToLower(r))
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

// accent 写默认角色色（chatui.DefaultChar）推出来的阶梯，亮暗各一套（深色有自己的配方，所以不能在网页里拿亮色配方现算）：
// 你的气泡 = soft 底 + line 细边，和 mygo 的 chatui.Host.accentOf 一样。换角色色时网页再按配方换算（第 3 步以后）。
func accent(b *bytes.Buffer, a design.Accent) {
	for _, kv := range []struct {
		name string
		c    ui.Color
	}{
		{"base", a.Base}, {"hover", a.Hover}, {"press", a.Press}, {"soft", a.Soft}, {"soft-hover", a.SoftHover},
		{"line", a.Line}, {"text", a.Text}, {"on", a.On}, {"strong", a.Strong}, {"on-strong", a.OnStrong},
	} {
		v, _ := cssValue(kv.c)
		fmt.Fprintf(b, "  --accent-%s: %s;\n", kv.name, v)
	}
}

// chat 写聊天区推出来的量里网页气泡要用的那几个（只写数，单位由使用处配）。
func chat(b *bytes.Buffer, t chatui.Tokens) {
	for _, kv := range []struct {
		name string
		v    any
	}{
		{"avatar-msg", t.AvatarMsg}, {"bubble-pad-v", t.BubblePadV}, {"bubble-pad-h", t.BubblePadH},
		{"gap-in-group", t.GapInGroup}, {"gap-groups", t.GapGroups}, {"join-window", t.JoinWindow},
		{"body", t.Body}, {"body-line", t.BodyLine}, {"name-line", t.NameLine}, {"info-line", t.InfoLine},
		{"r1", t.R1}, {"r-join", t.RJoin}, {"s1", t.S1}, {"s2", t.S2}, {"s3", t.S3},
	} {
		if v, ok := cssValue(kv.v); ok {
			fmt.Fprintf(b, "  --chat-%s: %s;\n", kv.name, v)
		}
	}
	// 头像色板（chatui.CharColors，按名字散列取一个，和 mygo 的 avatarIndexOf 一样分 8 种）
	for i, c := range chatui.CharColors {
		if v, ok := cssValue(c.Color()); ok {
			fmt.Fprintf(b, "  --chat-avatar-%d: %s;\n", i, v)
		}
	}
}
